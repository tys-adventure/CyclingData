import assert from 'node:assert/strict';
import {buildCoachWeek,coachBaseline,validateCoachProfile} from '../public/coach.js';
import {coachEvidence,coachTime} from '../public/coach-load.js';
const now=new Date(2026,9,14,12),week=new Date(2026,9,12),race={id:'race',name:'Test event',race_date:'2027-05-14',race_end_date:'2027-05-16',race_type:'road'};
const profile=validateCoachProfile({experience:'intermediate',available_days:[1,3,5,6],weekly_minutes:600,long_minutes:240,long_day:6,planning_mph:12,baseline_miles:null,target_race_id:'race',started_week:'2026-10-12'});
const history=[7,14,21,28].map((days,i)=>({id:'history'+i,started_at:new Date(2026,9,12-days,8).toISOString(),duration_s:120*60,distance_m:20000,elevation_m:100}));
const make=extra=>buildCoachWeek({profile,races:[race],rides:history,week,now,...extra});
assert.equal(coachBaseline(profile,history,now).minutes,120);
assert.equal(make().targetMinutes,120);
assert.equal(make({profile:{...profile,planning_mph:25}}).targetMinutes,120);
assert.equal(make({rides:history.map(r=>({...r,distance_m:r.distance_m*3}))}).targetMinutes,120);
assert.equal(coachTime(35),'35 min');assert.equal(coachTime(95),'1 hr 35 min');assert.equal(coachTime(120),'2 hrs');
const ride={id:'new',started_at:new Date(2026,9,14,8).toISOString(),duration_s:3600,distance_m:10000,elevation_m:700};
const zones={ftp:200,hr_z2:120,hr_z3:140,hr_z4:160,hr_z5:180};
const stream=watts=>({summary:{device_watts:true},streams:{time:Array.from({length:61},(_,i)=>i*60),watts:Array(61).fill(watts)}});
const easy=make({rides:[...history,ride],zones,recordings:{new:stream(120)}});
const hard=make({rides:[...history,ride],zones,recordings:{new:stream(240)}});
assert.ok(hard.targetMinutes<easy.targetMinutes);
assert.equal(hard.evidence.highMinutes,60);assert.equal(hard.evidence.powerRides,1);assert.equal(hard.evidence.hardWithin48h,true);
assert.equal(hard.actual.elevation,700);
assert.ok(hard.days.filter(d=>d.kind==='suggestion'&&d.date<='2026-10-15').every(d=>d.session_type==='easy'));
const missing=make({rides:[...history,ride],zones,recordings:{}});
assert.equal(missing.evidence.unknownRides,1);assert.equal(missing.evidence.analyses.length,0);
assert.equal(coachEvidence({rides:[ride],zones,now,recordings:{new:{...stream(240),summary:{device_watts:false}}}}).analyses.length,0);
const hrOnly={streams:{time:Array.from({length:61},(_,i)=>i*60),heartrate:Array(61).fill(170)}};
assert.equal(coachEvidence({rides:[ride],zones,now,recordings:{new:hrOnly}}).hrRides,1);
const patchy={streams:{time:[0,60,3600],watts:[240,240,240]}};
assert.equal(coachEvidence({rides:[ride],zones,now,recordings:{new:patchy}}).analyses.length,0);
const tired=make({checkin:{recovery:'tired'}});
assert.ok(tired.targetMinutes<make().targetMinutes);
assert.equal(make().consistency.activeWeeks,4);
assert.equal(make({rides:[...history,ride,{...ride,id:'same-day'}]}).consistency.daysActual,1);
assert.equal(make({rides:history.slice(0,1),week:new Date(2026,9,19)}).targetMinutes,make({rides:history.slice(0,1)}).targetMinutes);
const longRide={...ride,duration_s:120*60,distance_m:1000};
assert.ok(make({rides:[...history,longRide]}).suggestions.every(d=>d.session_type==='rest'));
assert.ok(make({rides:[...history,ride],sessions:[{session_date:'2026-10-15',duration_min:90,status:'planned'}]}).reviewCalendar);
console.log('Time-first targets, intensity evidence/fallbacks, duration formatting, recovery, consistency, terrain context, and preserved budgets passed.');
