import assert from 'node:assert/strict';
import fs from 'node:fs';
import {validateReleases,renderPage,renderRelease,releaseDate,filterReleases} from '../lib/release-notes.mjs';
import {requiresReleaseNotes,checkReleaseDelta} from '../scripts/check-release-notes.mjs';
const releases=JSON.parse(fs.readFileSync(new URL('../public/releases.json',import.meta.url),'utf8'));
assert.equal(validateReleases(releases),releases);
assert.equal(releaseDate('2026-11-11'),'November 11, 2026');
assert.equal(filterReleases(releases,'FIT').some(r=>r.id==='bring-your-rides'),true);
assert.equal(filterReleases(releases,'November 2026').length,2);
assert.equal(filterReleases(releases,'strava permission','fixed').length,1);
assert.equal(filterReleases(releases,'nonsensical search').length,0);
assert.equal(filterReleases(releases,'  RECOVERY  check-ins ').some(r=>r.id==='a-week-that-moves-with-you'),true);
const html=renderPage(releases);
assert.equal((html.match(/data-release-id=/g)||[]).length,releases.length);
assert.ok(html.includes('Still in the workshop.'));assert.ok(html.includes('Awaiting access'));assert.ok(html.includes('<noscript>'));
const escaped=renderRelease({...releases[0],title:'<script>bad</script>',changes:[{type:'new',title:'<img onerror=x>',text:'A & B'}]},0);
assert.ok(escaped.includes('&lt;script&gt;bad&lt;/script&gt;'));assert.ok(!escaped.includes('<img onerror=x>'));assert.ok(escaped.includes('A &amp; B'));
assert.throws(()=>validateReleases([...releases,releases[0]]),/IDs/);
assert.throws(()=>validateReleases([{...releases[0],date:'2026-02-30'}]),/dates/);
assert.throws(()=>validateReleases([{...releases[0],changes:[{type:'pending',title:'x',text:'x'}]}]),/supported type/);
assert.equal(requiresReleaseNotes(['docs/guide.md','tests/a.test.mjs']),false);
assert.equal(requiresReleaseNotes(['ios/README.md','public/releases.html']),false);
assert.equal(requiresReleaseNotes(['public/app.js']),true);
assert.throws(()=>checkReleaseDelta(['public/app.js'],releases,releases),/release-note update/);
assert.throws(()=>checkReleaseDelta(['public/app.js','public/releases.json'],releases,structuredClone(releases)),/release-note update/);
assert.doesNotThrow(()=>checkReleaseDelta(['public/app.js','public/releases.json'],[{...releases[0],title:'A new update'},...releases.slice(1)],releases));
assert.doesNotThrow(()=>checkReleaseDelta(['README.md'],releases,releases));
console.log('Release history, date handling, search/filtering, static rendering, escaping, and semantic release-update guard passed.');
