import assert from 'node:assert/strict';
import {validateZones,zoneDefinitions,classifyZone,timeInZones} from '../public/zones.js';
const settings=validateZones({ftp:200,hr_z2:120,hr_z3:140,hr_z4:160,hr_z5:180});
const p=zoneDefinitions(settings,'power'),h=zoneDefinitions(settings,'hr');
assert.equal(p.length,7);assert.equal(h.length,5);
assert.equal(classifyZone(110,p),0);assert.equal(classifyZone(111,p),1);
assert.equal(classifyZone(300,p),5);assert.equal(classifyZone(301,p),6);
assert.equal(classifyZone(119,h),0);assert.equal(classifyZone(120,h),1);
assert.equal(classifyZone(180,h),4);
const streams={time:[0,10,30,35,200,210,220],watts:[0,150,null,200,400,100,250],heartrate:[100,130,null,170,190,0,150]};
const watts=timeInZones(streams,'power',settings);
assert.deepEqual(watts.seconds,[20,20,0,0,0,0,10]);
assert.equal(watts.covered,50);assert.equal(watts.skipped,170);
const hr=timeInZones(streams,'hr',settings);
assert.deepEqual(hr.seconds,[10,20,0,0,10]);assert.equal(hr.covered,40);assert.equal(hr.skipped,180);
assert.equal(timeInZones({},'power',settings).covered,0);
assert.equal(timeInZones({time:[0],watts:[200]},'power',settings).covered,0);
assert.equal(timeInZones({time:[0,20],watts:[undefined,200]},'power',settings).covered,0);
assert.equal(timeInZones({time:[0,10],watts:[6000,200]},'power',settings).covered,0);
assert.equal(timeInZones({time:[0,10],heartrate:[0,100]},'hr',settings).covered,0);
assert.equal(timeInZones({time:[10,5],watts:[100,100]},'power',settings).covered,0);
assert.deepEqual(validateZones({}),{ftp:null,hr_z2:null,hr_z3:null,hr_z4:null,hr_z5:null});
assert.deepEqual(zoneDefinitions(null,'hr'),[]);
for(const bad of [{ftp:20},{ftp:200.1},{hr_z2:100},{hr_z2:120,hr_z3:120,hr_z4:160,hr_z5:180},{hr_z2:120,hr_z3:140,hr_z4:160,hr_z5:301}])assert.throws(()=>validateZones(bad));
console.log('Zone boundary, duration weighting, missing-data, and validation checks passed.');
