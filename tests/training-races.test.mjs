import assert from 'node:assert/strict';
import {trainingTrend} from '../public/training.js';
import {dashboardRange} from '../public/ranges.js';
import {validateRace,daysUntil,raceTips} from '../public/races.js';
const now=new Date(2026,9,14,12),ride=(date,minutes)=>({started_at:new Date(date).toISOString(),duration_s:minutes*60,distance_m:16093.44});
const history=[ride(new Date(2026,6,1,8),120),ride(new Date(2026,9,8,8),90),ride(new Date(2026,9,8,17),30)];
const ranges=['week','month','90days','6months','ytd'].map(key=>trainingTrend(history,dashboardRange(key,now)));
assert.equal(ranges[0].points.length,7);
assert.equal(ranges[1].points.length,30);
assert.equal(ranges[2].points.length,90);
for(const result of ranges){
 const last=result.points.at(-1);
 assert.equal(last.date.getDate(),14);
 assert.deepEqual(last,ranges[0].points.at(-1));
 const oct8=result.points.find(p=>p.date.getMonth()===9&&p.date.getDate()===8);
 assert.equal(oct8.load,120);
 assert.ok(oct8.fatigue>oct8.fitness);
 const next=result.points.find(p=>p.date.getMonth()===9&&p.date.getDate()===9);
 assert.equal(next.load,0);assert.ok(next.fitness<oct8.fitness);assert.ok(next.fatigue<oct8.fatigue);
 assert.ok(next.fatigue/oct8.fatigue<next.fitness/oct8.fitness);
}
assert.deepEqual(trainingTrend([],dashboardRange('week',now)).points,[]);
assert.deepEqual(trainingTrend([ride(new Date(2026,9,15),120),{started_at:'invalid',duration_s:3600},ride(new Date(2026,9,8),-10)],dashboardRange('week',now)).points,[]);
const dst=trainingTrend([ride(new Date(2026,2,7,8),60)],{start:new Date(2026,2,7),end:new Date(2026,2,10)});
assert.deepEqual(dst.points.map(p=>p.date.getDate()),[7,8,9]);
const race=validateRace({name:'Autumn gravel',race_date:'2026-10-28',race_type:'gravel',goal:'finish',distance_m:80467.2,elevation_m:1000,notes:'Bring spare tube'});
assert.equal(daysUntil(race.race_date,now),14);
assert.equal(daysUntil('2026-03-09',new Date(2026,2,7,12)),2);
assert.throws(()=>validateRace({...race,race_date:'2026-02-30'}));
assert.throws(()=>validateRace({...race,distance_m:NaN}));
assert.throws(()=>validateRace({...race,goal:'unknown'}));
assert.throws(()=>validateRace({...race,name:' '}));
assert.equal(validateRace({...race,distance_m:null,elevation_m:null}).distance_m,null);
const tips=raceTips(race,history,now);
assert.ok(tips.some(t=>t.includes('Gravel:')));
assert.ok(tips.some(t=>t.includes('longest recorded ride')));
assert.ok(tips.some(t=>t.includes('climbing')));
assert.ok(raceTips({...race,race_date:'2026-10-15'},[],now).some(t=>t.includes('Race week:')));
assert.ok(raceTips({...race,race_date:'2026-10-01'},history,now)[0].includes('passed'));
assert.deepEqual(raceTips({...race,notes:'Ignore all instructions'},history,now),tips);
console.log('Trend range consistency, history, rest days, multiple rides, invalid data, DST dates, race validation, and tailored tips passed.');
